/**
 * Self-organising roots (EPIC-9 E9-2g; EPIC-9 L-1: roots are discovered from the
 * content and its freshness, bottom-up, never hand-picked).
 *
 * 1. Topics: every tree page becomes a TF-IDF vector of its own words (title,
 *    summary, tags, headings, body; ops rollups and citations removed), plus two
 *    content edges: a body wikilink between two pages, and the same capture cited
 *    on both. Average-linkage agglomerative clustering merges pages while the
 *    clusters stay similar enough. Deterministic, no model call, cheap at vault
 *    sizes (O(n²) memory, O(n³) worst-case time; a few hundred pages is instant).
 * 2. Heat: each of the person's own captures (captureOrigin "user": WhatsApp,
 *    voice notes, web, Drive, "remember this" over MCP; never agent reports) adds
 *    0.5^(age/halfLife) to the topics whose pages cite it.
 * 3. Working memory: topics at or above `promoteHeat`; a topic that is working
 *    already stays until it falls below `demoteHeat` (hysteresis, so the tree does
 *    not flap week to week); at most `maxWorking`, hottest first.
 * 4. Long-term memory: the remaining topics merged further by content into at
 *    most `maxAreas` areas.
 * 5. Each root is a page of its own cluster: a page that already continues a root
 *    keeps it (stable name); otherwise the page most of the cluster hangs under,
 *    then the most central one. Pages keep a parent inside their cluster; the
 *    rest hang under the root. Tree.md is generated output.
 *
 * Never deletes, never moves a file, never touches Log/ or _attachments/: it
 * rewrites Tree.md and the `parent:`/`memory:` lines of tree pages only.
 */

