const DAY_MS = 86_400_000;
const daysBetween = (from: string, to: string) => Math.round((Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / DAY_MS);

/** "Maresme vs Cerdanya House Decision 2026-07-24" → "Maresme vs Cerdanya House Decision"; "X — subtitle" → "X". */
export function cleanTopicName(title: string): string {
  let name = title.replace(/\s+[—–]\s+.*$/, "").replace(/\s*\([^)]*\)\s*$/, "");
  name = name.replace(/[\s_-]+(?:(?:jan(?:uary)?|feb(?:ruary)?|mar(?:ch)?|apr(?:il)?|may|june?|july?|aug(?:ust)?|sept?(?:ember)?|oct(?:ober)?|nov(?:ember)?|dec(?:ember)?)\.?\s+)?\d{4}(?:-\d{2}){0,2}$/i, "").replace(/^\d{4}(?:-\d{2}){0,2}[\s_-]+/, "");
  name = name.replace(/[|[\]#^]+/g, " ").replace(/_/g, " ").replace(/\s+/g, " ").trim();
  if (name && name === name.toLowerCase()) name = name.charAt(0).toUpperCase() + name.slice(1);
  return name || title.trim();
}

/** Remember how each term is written, so a name built from terms reads as the person wrote them. */
function collectSurfaces(into: Map<string, Map<string, number>>, text: string, weight: number): void {
  for (const word of text.normalize("NFKC").split(/[^\p{L}\p{N}]+/u)) {
    if (word.length < 3) continue;
    const [term] = tokens(word);
    if (!term || FILLER.has(term)) continue;
    const forms = into.get(term) ?? new Map<string, number>();
    const form = word.length > 4 && /s$/i.test(word) && !/ss$/i.test(word) ? word.slice(0, -1) : word;
    forms.set(form, (forms.get(form) ?? 0) + weight);
    into.set(term, forms);
  }
}

function weigh(into: Map<string, number>, text: string, weight: number): void {
  for (const token of tokenList(text)) into.set(token, (into.get(token) ?? 0) + weight);
}

/**
 * Words that say how something was said or ingested, not what about: spoken filler
 * from voice notes (English and Spanish) and the extraction/ingest vocabulary. Without
 * this, two rambling voice notes look alike whatever their subject.
 */
