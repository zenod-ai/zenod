async function writeFixture(root: string): Promise<void> {
  for (const file of fixtureFiles()) {
    await mkdir(dirname(join(root, file.path)), { recursive: true });
    await writeFile(join(root, file.path), file.content);
  }
}

describe("E9-2h agent-report shapes", () => {
  it("catches ticket and run ids in parentheses, repo-name heads and console shapes", () => {
    const reports = [
      AGENT_REPORT,
      "Run: run_801e2432 E9-2h polish of the tree, merged and live",
      "zenod-social, 2026-10-28: Reddit writes from the Team Browser go out only through the approval queue.",
      "infra-vps EPIC-15 Watcher read 2026-10-29: 22 of 22 services running.",
      "VPS1 2026-10-30: In-control DOD-3 went RED on swap slope.",
      "Keys rotated for the rehearsal (T3); Stripe still pending (E7-A12).",
      "[agent_team] console decision: every wake goes through the runner.",
      "Decision 2026-11-02 (agent_team EPIC-51 E51-A1): the paper style.",
    ];
    for (const text of reports) {
      expect(captureOrigin("mcp", text), text).toBe("agent");
      expect(isAgentOpsReport(text, "mcp"), text).toBe(true);
    }
    // Forwarded over WhatsApp, a report still files as ops when its first line carries an id and reads as telemetry.
    expect(isAgentOpsReport(AGENT_REPORT, "whatsapp")).toBe(true);
  });

  it("leaves people's own notes alone", () => {
    const notes = [
      "Remember that I take my coffee as a flat white",
      "Epic Social post idea: why every agent team needs a spine; draft it for Reddit and X.",
      "follow-up call with Ana about the house in Maresme",
      "Hair transplant: budget ceiling 4k, prefer spring timing.",
      "Jordi's 2023 Barcelona hair-transplant quotes, prices from three clinics.",
    ];
    for (const text of notes) {
      expect(captureOrigin("mcp", text), text).toBe("user");
      expect(isAgentOpsReport(text, "mcp"), text).toBe(false);
    }
    // A person's own voice note naming an ask is theirs.
    expect(isAgentOpsReport("Approve E7-A12, go ahead with Stripe", "whatsapp")).toBe(false);
    expect(captureOrigin("whatsapp", AGENT_REPORT)).toBe("user");
  });
});

describe("E9-2h tree polish", { timeout: 60_000 }, () => {
  let dir: string;
  beforeEach(async () => { dir = await mkdtemp(join(tmpdir(), "zenod-e92h-")); });
  afterEach(async () => { await rm(dir, { recursive: true, force: true }); });

  it("names roots for what their pages are about, merges near-duplicates and calls older work on a working subject 'earlier'", async () => {
    await writeFixture(dir);
    const plan = (await discoverTree(dir, { today: "2026-11-02" }))!;
    expect(plan.fresh).toBe(false);
    const names = plan.roots.map(r => `${r.kind}:${r.name}`);
    // One working root for the product; the warm deck topic, titled after it, is part of it.
    expect(plan.roots.filter(r => r.kind === "working").map(r => r.name)).toEqual(["Nimbus"]);
    expect(plan.memory.get("Notes/Deck gallery.md")).toBe("working");
    expect(plan.memory.get("Projects/Launch deck.md")).toBe("working");
    // The older docs are named for what they share (the product), not after the connector page they hang under.
    expect(names).toContain("long-term:Nimbus (earlier)");
    expect(names.some(n => /whatsapp/i.test(n))).toBe(false);
  });

  it("moves an agent-report leaf to the ops rollup and Archive/, byte for byte, never into a root's freshness", async () => {
    await writeFixture(dir);
    const leaf = "Notes/es-proof-fake-04c5 (agent_team E46-S9 production-proo.md";
    const leafBytes = await readFile(join(dir, leaf), "utf8");
    const logBefore = await Promise.all(Object.keys(LOGS).map(p => readFile(join(dir, p), "utf8")));
    const report = await runTreeSweep(dir, { today: "2026-11-02" });
    expect(report.counts.agentLeavesRefiled).toBe(1);
    const files = await listMarkdownFiles(dir);
    expect(files).not.toContain(leaf);
    const archived = files.find(f => f.startsWith(`${ARCHIVE_AGENT_LEAVES_DIR}/`))!;
    expect(await readFile(join(dir, archived), "utf8")).toBe(leafBytes);
    // One dated ops line on a tree page (the root it read most like when it was re-filed) carries the report now.
    const roots = (await readTree(dir))!.nodes;
    const pageTexts = await Promise.all(files.filter(f => /^(?:Projects|Notes|Areas)\//.test(f)).map(f => readFile(join(dir, f), "utf8")));
    expect(pageTexts.filter(t => /## Ops rollup[\s\S]*- 2026-11-02 ops \(1\): \[\[2026-11-02#\^e-c00001\]\]/.test(t))).toHaveLength(1);
    expect(roots.length).toBeGreaterThan(0);
    // The Log is untouched, lint is clean, and the sweep's raw-data guard accepts the move.
    expect(await Promise.all(Object.keys(LOGS).map(p => readFile(join(dir, p), "utf8")))).toEqual(logBefore);
    expect((await lintTree(dir)).issues.filter(i => i.severity === "error")).toEqual([]);
    expect(() => assertSweepChangesSafe([
      { path: leaf, before: leafBytes, after: null },
      { path: archived, before: null, after: leafBytes },
    ])).not.toThrow();
    // A bare delete of a page, or a copy that is not byte for byte, is refused.
    expect(() => assertSweepChangesSafe([{ path: leaf, before: leafBytes, after: null }])).toThrow(/delete_refused/);
    expect(() => assertSweepChangesSafe([
      { path: leaf, before: leafBytes, after: null },
      { path: archived, before: null, after: `${leafBytes}x` },
    ])).toThrow(/delete_refused/);
  });

  it("keeps a provisional leaf that holds one of the person's own captures", async () => {
    await writeFixture(dir);
    const own = "Notes/Own leaf.md";
    await writeFile(join(dir, own), page("Own leaf", "Projects/Launch deck", "A note ([[2026-10-30#^e-b00003]]).", ["provisional: true"]));
    const moved = await refileAgentLeaves(dir, new TrackedWrites(dir));
    expect(moved.map(m => m.path)).toEqual(["Notes/es-proof-fake-04c5 (agent_team E46-S9 production-proo.md"]);
    expect(await listMarkdownFiles(dir)).toContain(own);
  });

  it("a second run writes nothing and the names stay", async () => {
    await writeFixture(dir);
    const writes = new TrackedWrites(dir);
    await refileAgentLeaves(dir, writes);
    const first = (await rediscoverTree(dir, "2026-11-02", writes))!;
    const again = (await discoverTree(dir, { today: "2026-11-02" }))!;
    expect(again.roots.map(r => [r.name, r.kind])).toEqual(first.roots.map(r => [r.name, r.kind]));
    expect(await refileAgentLeaves(dir, new TrackedWrites(dir))).toEqual([]);
    const second = (await rediscoverTree(dir, "2026-11-02", new TrackedWrites(dir)))!;
    expect(second.changed).toEqual([]);
  });
});
