/**
 * EPIC-9 E9-2h: the rough edges Jordi's re-rooted vault showed after E9-2g, in a
 * made-up vault. Last run (Tree.md generated by discovery) named an area of older
 * product docs after one page ("WhatsApp connector"), kept a warm "Launch deck" topic
 * next to "Nimbus" (the product), and an agent's test-campaign report, whose ticket id
 * sat in parentheses, became a provisional leaf.
 */
const CONFIG = "schema_version: 1\ntags:\n  - work\nconfidence_threshold: 0.7\n";
const INDEX = "---\ntitle: Index\n---\n\n# Index\n\nTop of the vault.\n";

const page = (title: string, parent: string, body: string, extra: string[] = []) => [
  "---", `title: ${title}`, "type: note", "tags: []", "created: 2026-07-01", "updated: 2026-07-01",
  `summary: ${title}.`, `parent: "[[${parent}]]"`, ...extra, "---", "", `# ${title}`, "", body, "",
].join("\n");

const entry = (time: string, anchor: string, source: string, text: string) =>
  `## ${time} ${text.slice(0, 30)}  ^${anchor}\n- source: ${source}\n- verbatim: no\n\n> ${text}\n`;

const AGENT_REPORT = "es-proof-fake-04c5 (agent_team E46-S9 production-proof campaign, fake tester): the Writer drafted the first post P-0001 for X; nothing posted.";

const LOGS: Record<string, string> = {
  "Log/2026-07-05.md": `# 2026-07-05\n\n${entry("09:00", "e-a00001", "whatsapp", "Nimbus librarian acceptance tests pass on the vault")}\n${entry("10:00", "e-a00002", "whatsapp", "Nimbus herald briefing draft for the librarian")}`,
  "Log/2026-10-25.md": `# 2026-10-25\n\n${entry("09:00", "e-b00001", "whatsapp", "Nimbus pricing: three tiers, memory for teams")}`,
  "Log/2026-10-30.md": `# 2026-10-30\n\n${entry("09:00", "e-b00002", "whatsapp", "Nimbus launch checklist: signup, onboarding, pricing page")}\n${entry("10:00", "e-b00003", "whatsapp", "Nimbus launch deck: slides for investors, the story order")}`,
  "Log/2026-11-01.md": `# 2026-11-01\n\n${entry("09:00", "e-b00004", "whatsapp", "Nimbus launch deck gallery: every slide in one view for investors")}\n${entry("10:00", "e-b00005", "whatsapp", "Nimbus memory onboarding for the first paying teams")}`,
  "Log/2026-11-02.md": `# 2026-11-02\n\n${entry("03:10", "e-c00001", "mcp", AGENT_REPORT)}`,
};

const OLD_TREE = [
  "---", "title: Tree", "updated: 2026-11-01", `generated: ${DISCOVERY_GENERATOR}`, "---", "", "# Memory tree", "",
  "## Working memory", "",
  "- Nimbus | working | [[Projects/Nimbus]] | Product.",
  "- Launch deck | working | [[Projects/Launch deck]] | Deck.",
  "", "## Long-term memory", "",
  "- WhatsApp connector | long-term | [[Notes/WhatsApp connector]] | Older docs.",
  "",
].join("\n");

