// E14-S4 local check, the browser half: Personas tab, Run now, the finding in the Inbox.
import { chromium } from "playwright-core";
const OUT = process.argv[2];
const BASE = `http://127.0.0.1:${process.argv[3]}`;
const exe = process.env.HOME + "/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome";
const browser = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("pageerror", e.message));
await page.goto(`${BASE}/dev-login`);
await page.getByText("Has not run yet.").waitFor();
await page.screenshot({ path: `${OUT}/01-personas-before.png`, fullPage: true });
await page.getByRole("button", { name: "Run now" }).click();
await page.getByText(/wrote a recap and posted one finding/).waitFor({ timeout: 30000 });
await page.waitForTimeout(600);
console.log("last run:", (await page.locator(".zr-run").innerText()).replace(/\s+/g, " "));
console.log("tab after run:", await page.getByRole("tab", { name: /Inbox/ }).innerText());
await page.screenshot({ path: `${OUT}/02-personas-after-run.png`, fullPage: true });
console.log("vault:", JSON.stringify(await (await page.request.get(`${BASE}/dev/commits`)).json()));
await page.getByRole("link", { name: "in your inbox" }).click();
await page.getByText("You mentioned the dentist twice this week").waitFor();
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/03-inbox-finding.png`, fullPage: true });
const m = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const mp = await m.newPage();
await mp.goto(`${BASE}/dev-login`);
await mp.getByText(/wrote a recap/).waitFor();
await mp.waitForTimeout(800);
await mp.screenshot({ path: `${OUT}/04-phone.png`, fullPage: true });
await browser.close();
