// E12-S13 local check: ask in the chat, follow "Show in graph", watch the answer light up.
import { chromium } from "playwright-core";
const BASE = process.argv[3] ?? "http://127.0.0.1:18943";
const OUT = process.argv[2];
const Q = "How are we financing Westcombe?";
const exe = process.env.HOME + "/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome";
const browser = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const timings = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1, recordVideo: { dir: OUT + "/video", size: { width: 1440, height: 960 } } });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("pageerror", e.message));
page.on("response", (r) => { if (r.url().includes("memory-graph?lit")) timings.push(Math.round(r.request().timing().responseEnd)); });
await page.goto(`${BASE}/dev-login`);
await page.waitForSelector("textarea");
await page.waitForTimeout(800);
await page.locator("textarea").pressSequentially(Q, { delay: 35 });
await page.keyboard.press("Enter");
await page.waitForSelector("[data-testid=show-in-graph]");
await page.waitForTimeout(1200);
await page.screenshot({ path: `${OUT}/01-chat.png` });
await page.locator("[data-testid=show-in-graph]").hover();
await page.waitForTimeout(500);
await page.locator("[data-testid=show-in-graph]").click();
await page.waitForSelector("svg.zp-g .zp-glit");
await page.waitForTimeout(700);
await page.screenshot({ path: `${OUT}/02-lighting.png` });
await page.waitForTimeout(2600);
await page.screenshot({ path: `${OUT}/03-lit.png` });
const lit = await page.$$eval("svg.zp-g .zp-glit", (els) => els.map((e) => e.getAttribute("aria-label")));
const litEdges = await page.$$eval("svg.zp-g line.zp-glitedge", (els) => els.length);
const hash = await page.evaluate(() => location.hash);
// Open one lit memory: the graph moves to it with its neighbours.
await page.getByRole("button", { name: /^Financing notes Oct 2023, / }).first().click();
await page.waitForSelector(".zp-gpanel .zp-gnote, .zp-gpanel .zp-hint");
await page.waitForTimeout(1800);
await page.screenshot({ path: `${OUT}/04-opened.png` });
const opened = await page.locator(".zp-gpanel h3").textContent();
await page.goBack();
await page.waitForSelector("svg.zp-g .zp-glit");
await page.waitForTimeout(2800);
const backLit = await page.$$eval("svg.zp-g .zp-glit", (els) => els.length);
await ctx.close();
// Phone.
const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const p2 = await phone.newPage();
await p2.goto(`${BASE}/dev-login`);
await p2.waitForSelector("textarea");
await p2.goto(`${BASE}/${hash}`);
await p2.waitForSelector("svg.zp-g .zp-glit");
await p2.waitForTimeout(3200);
await p2.screenshot({ path: `${OUT}/05-phone.png` });
await phone.close();
await browser.close();
console.log(JSON.stringify({ lit, litEdges, opened, backLit, timings, hash: decodeURIComponent(hash) }, null, 1));
