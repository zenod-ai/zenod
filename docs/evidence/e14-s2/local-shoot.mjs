import { chromium } from "playwright-core";
const BASE = `http://127.0.0.1:${process.argv[3]}`;
const OUT = process.argv[2];
const exe = process.env.HOME + "/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome";
const browser = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("pageerror", e.message));
await page.goto(`${BASE}/dev-login`);
await page.getByText("Nothing needs you.").waitFor();
await page.screenshot({ path: `${OUT}/01-empty.png` });
await page.getByRole("button", { name: "Show examples" }).click();
await page.locator("[data-testid=inbox-item]").nth(3).waitFor();
await page.waitForTimeout(800);
console.log("tab after examples:", await page.getByRole("tab", { name: /Inbox/ }).innerText());
await page.screenshot({ path: `${OUT}/02-examples.png`, fullPage: true });
// A persona question and a desk job, posted through the internal API later steps use.
const q = await (await page.request.post(`${BASE}/dev/persona-question`)).json();
const j = await (await page.request.post(`${BASE}/dev/desk-job`)).json();
await page.reload();
await page.getByText(q.title).waitFor();
console.log("tab with new items:", await page.getByRole("tab", { name: /Inbox/ }).innerText());
await page.request.post(`${BASE}/dev/desk-job/step`, { data: { id: j.id, step: "Moving 7 memories to Garden" } });
await page.getByText("Moving 7 memories to Garden").waitFor({ timeout: 12000 });
console.log("job step moved on its own: yes");
const card = page.locator("[data-testid=inbox-item]", { hasText: q.title });
await card.getByRole("button", { name: "Yes, one memory" }).click();
await card.getByText("Saved as a memory.").waitFor();
const done = page.locator("[data-testid=inbox-item]", { hasText: "Split Boat repair" });
await done.getByRole("button", { name: "See the changes" }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/03-answered-and-changes.png`, fullPage: true });
await done.getByRole("button", { name: "Undo" }).click();
await done.getByRole("button", { name: "Yes, put it back" }).click();
await done.getByText(/^Undone\. /).waitFor();
console.log("tab at end:", await page.getByRole("tab", { name: /Inbox/ }).innerText());
const m = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const mp = await m.newPage();
await mp.goto(`${BASE}/dev-login`);
await mp.locator("[data-testid=inbox-item]").first().waitFor();
await mp.waitForTimeout(800);
await mp.screenshot({ path: `${OUT}/04-phone.png`, fullPage: true });
await browser.close();
